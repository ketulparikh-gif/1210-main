// Helper to get all data for any selected watershed region
export function getRegionDataset(regionId: string) {
  if (regionId === 'narmada') {
    const region = WATERSHED_REGIONS.find((r) => r.id === 'narmada') || WATERSHED_REGIONS[1];
    return {
      region,
      gauges: NARMADA_GAUGES,
      camps: NARMADA_CAMPS,
      alerts: NARMADA_ALERTS,
      forecastData: NARMADA_FORECAST,
      impactNodes: NARMADA_IMPACT,
      riskFactors: NARMADA_RISK_FACTORS,
    };
  }

  if (regionId === 'tapi') {
    const region = WATERSHED_REGIONS.find((r) => r.id === 'tapi') || WATERSHED_REGIONS[2];
    return {
      region,
      gauges: TAPI_GAUGES,
      camps: TAPI_CAMPS,
      alerts: TAPI_ALERTS,
      forecastData: TAPI_FORECAST,
      impactNodes: TAPI_IMPACT,
      riskFactors: TAPI_RISK_FACTORS,
    };
  }

  // Default: Sabarmati
  const region = WATERSHED_REGIONS.find((r) => r.id === 'sabarmati') || WATERSHED_REGIONS[0];
  return {
    region,
    gauges: INITIAL_GAUGES,
    camps: RESCUE_CAMPS,
    alerts: INITIAL_ALERTS,
    forecastData: FORECAST_TRAJECTORY,
    impactNodes: IMPACT_CHAIN,
    riskFactors: INITIAL_RISK_FACTORS,
  };
}

